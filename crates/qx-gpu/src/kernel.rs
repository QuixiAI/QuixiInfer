//! QuixiInfer's CUDA C++ kernels as CubeCL kernels.
//!
//! Burn's `SourceKernel` names every entry point `main`, which CUDA forbids for a `__global__`
//! function, so QuixiInfer implements `CubeKernel` itself and names the entry point explicitly.
//!
//! Launch arguments, in order: the buffers given to the launch, then a device pointer to the
//! `u64` info words (when any were given). On devices with grid constants CubeCL appends the
//! info words by value as well; a kernel that does not declare that parameter never reads it.
//! Raw device addresses (VMM arenas, mapped host memory) travel in the info words.
use burn_cubecl::cubecl::{
    CubeKernel, PrecompiledSource,
    ir::{UIntKind, metadata::Info},
    prelude::*,
};

/// One flattened `kernels/*.cu` file, generated by `build.rs`.
#[derive(Clone, Copy, Debug)]
pub struct Module {
    pub name: &'static str,
    pub source: &'static str,
    /// FNV-1a of `source`, computed by `build.rs`; keys CubeCL's compilation cache.
    pub source_hash: u64,
    pub entries: &'static [&'static str],
}

impl Module {
    /// The kernel for `entry` with `threads` threads per block.
    pub fn kernel(&self, entry: &'static str, cube_dim: CubeDim) -> CudaSource {
        assert!(self.entries.contains(&entry), "kernels/{}.cu has no entry point {entry}", self.name);
        self.validate();
        CudaSource { module: *self, entry, cube_dim }
    }

    /// Compiles the module with NVRTC once per source (a marker under ~/.cache/quixiinfer remembers a source
    /// hash that compiled) and panics with the compiler's log if it fails. CubeCL reports a failed compilation
    /// only on the buffers a launch binds, and QuixiInfer's launches bind none (every address travels in the
    /// info words), so without this a kernel NVRTC rejects would silently launch nothing. nvcc checks the same
    /// text at build time, but the two compilers differ (NVRTC has no <cstdint>, for one).
    fn validate(&self) {
        use std::sync::{Mutex, OnceLock};
        static DONE: OnceLock<Mutex<std::collections::HashSet<u64>>> = OnceLock::new();
        let done = DONE.get_or_init(Default::default);
        if !done.lock().unwrap().insert(self.source_hash) {
            return;
        }
        let dir = std::env::var("HOME").ok().map(|h| std::path::PathBuf::from(h).join(".cache/quixiinfer/nvrtc-ok"));
        let marker = dir.as_ref().map(|d| d.join(format!("{}-{:016x}", self.name, self.source_hash)));
        if marker.as_ref().is_some_and(|m| m.exists()) {
            return;
        }
        // PTX only (a virtual architecture): the check is that NVRTC accepts the source, and a real target would make
        // NVRTC run ptxas over the whole module (10-20 minutes for mgemv.cu or moe.cu on 2026-11-07) before CubeCL's
        // own compile and the driver's JIT pay for the same SASS again
        let opts = cudarc::nvrtc::CompileOptions { options: vec![crate::mem::nvrtc_arch(true), "-lineinfo".into()], ..Default::default() };
        if let Err(e) = cudarc::nvrtc::compile_ptx_with_opts(self.source, opts) {
            panic!("kernels/{}.cu does not compile with NVRTC:\n{e}", self.name);
        }
        if let (Some(d), Some(m)) = (dir, marker) {
            let _ = std::fs::create_dir_all(&d).and_then(|_| std::fs::write(m, b""));
        }
    }
}

/// The modules compiled from `kernels/`.
pub mod modules {
    include!(concat!(env!("OUT_DIR"), "/kernels.rs"));
}

pub struct CudaSource {
    pub module: Module,
    pub entry: &'static str,
    pub cube_dim: CubeDim,
}

/// Set by `seal()`: every kernel the process will ever launch has been compiled and loaded, so a later compile is
/// a bug (see `CudaSource::source`).
pub static SEALED: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

/// Declares the kernel set complete. A server calls this after its warm-up has launched every window width it
/// can schedule; from then on a kernel that needs compiling aborts the process instead of silently launching
/// nothing.
pub fn seal() {
    SEALED.store(true, std::sync::atomic::Ordering::Relaxed);
}

impl KernelMetadata for CudaSource {
    fn id(&self) -> KernelId {
        KernelId::new::<CudaSource>().info((self.module.name, self.entry, self.module.source_hash, self.cube_dim))
    }
    fn address_type(&self) -> ElemType {
        UIntKind::U32.into()
    }
}

impl CubeKernel for CudaSource {
    fn define(&self) -> KernelDefinition {
        let settings = KernelSettings::new(self.cube_dim.0, ExecutionMode::Unchecked, AddressType::U32);
        KernelDefinition { body: Scope::root(settings.clone()), settings, info: Info::default() }
    }
    fn source(&self) -> Option<PrecompiledSource> {
        // CubeCL asks for the source only when the kernel id is not loaded yet, i.e. on an NVRTC compile. Each
        // compile costs about a second and leaks about 63 MiB of host memory inside NVRTC (2026-11-06), so a
        // steady state must never see this line. Worse, CubeCL reports a failed compile or module load only on
        // the buffers a launch binds, and these launches bind none: a kernel that cannot be loaded (the server
        // ran out of VRAM for the module after its graphs were captured, 2026-11-06) is retried on every launch
        // and the window silently runs without it. After `seal()` a compile is therefore fatal.
        if SEALED.load(std::sync::atomic::Ordering::Relaxed) {
            eprintln!(
                "fatal: kernel {}.cu {} (block {:?}) needs compiling after the kernel set was sealed: it was not warmed \
                 up, or its module failed to load (out of device memory?) and CubeCL is retrying it on every launch",
                self.module.name, self.entry, self.cube_dim
            );
            std::process::abort();
        }
        if std::env::var("QX_DS_VERBOSE").is_ok() {
            eprintln!("kernel load: {}.cu {} (block {:?})", self.module.name, self.entry, self.cube_dim);
        }
        Some(PrecompiledSource {
            source: self.module.source.to_string(),
            entrypoint_name: self.entry.to_string(),
            lang: "cuda",
        })
    }
}
