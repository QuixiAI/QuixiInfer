//! Flattens QuixiInfer's CUDA kernels and checks each one with nvcc.
//!
//! Every `kernels/*.cu` becomes one self-contained source: `#include "..."` lines are resolved inside
//! `kernels/` and inlined once each; any `#include <...>` is an error, because kernels depend on
//! nothing outside this repository. Each flattened source is compiled with nvcc for `sm_120a`, so a
//! kernel error fails `cargo build`, and the cubins stay in OUT_DIR. The generated `kernels.rs` holds
//! one constant per source and the list of its `extern "C" __global__` entry points.
use std::collections::HashSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn flatten(path: &Path, inc_dir: &Path, seen: &mut HashSet<PathBuf>, out: &mut String) {
    let canon = fs::canonicalize(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    if !seen.insert(canon.clone()) {
        return;
    }
    println!("cargo:rerun-if-changed={}", canon.display());
    let text = fs::read_to_string(&canon).unwrap();
    for (n, line) in text.lines().enumerate() {
        let t = line.trim_start();
        if t.starts_with("#pragma once") {
            continue;
        }
        if let Some(rest) = t.strip_prefix("#include") {
            let rest = rest.trim();
            if rest.starts_with('<') {
                panic!("{}:{}: system include {rest} is not allowed; kernels must be self-contained", canon.display(), n + 1);
            }
            let name = rest.trim_matches('"');
            let local = canon.parent().unwrap().join(name);
            let target = if local.exists() { local } else { inc_dir.join(name) };
            if !target.exists() {
                panic!("{}:{}: include \"{name}\" not found in kernels/", canon.display(), n + 1);
            }
            flatten(&target, inc_dir, seen, out);
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
}

/// Entry points: lines of the form `extern "C" __global__ [__launch_bounds__(...)] void [__launch_bounds__(...)] name(`.
fn entries(src: &str) -> Vec<String> {
    let mut v = Vec::new();
    for line in src.lines() {
        let Some(rest) = line.trim_start().strip_prefix("extern \"C\" __global__") else { continue };
        let mut rest = rest.trim_start();
        if let Some(r) = rest.strip_prefix("__launch_bounds__") {
            let close = r.find(')').expect("unclosed __launch_bounds__");
            rest = r[close + 1..].trim_start();
        }
        let mut rest = rest.strip_prefix("void").expect("entry points return void").trim_start();
        if let Some(r) = rest.strip_prefix("__launch_bounds__") {
            let close = r.find(')').expect("unclosed __launch_bounds__");
            rest = r[close + 1..].trim_start();
        }
        let name: String = rest.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
        assert!(!name.is_empty(), "could not parse entry point in: {line}");
        v.push(name);
    }
    v
}

fn fnv1a(s: &str) -> u64 {
    s.bytes().fold(0xcbf29ce484222325u64, |h, b| (h ^ b as u64).wrapping_mul(0x100000001b3))
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../kernels");
    let root = fs::canonicalize(&root).expect("kernels/ directory");
    let inc_dir = root.join("include");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("kernels");
    fs::create_dir_all(&out_dir).unwrap();
    println!("cargo:rerun-if-changed={}", root.display());
    println!("cargo:rerun-if-env-changed=QX_NVCC");
    println!("cargo:rerun-if-env-changed=QX_SKIP_NVCC");

    let mut sources: Vec<PathBuf> = fs::read_dir(&root)
        .unwrap()
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "cu"))
        .collect();
    sources.sort();

    let nvcc = std::env::var("QX_NVCC").unwrap_or_else(|_| "/usr/local/cuda-13.3/bin/nvcc".into());
    let skip = std::env::var("QX_SKIP_NVCC").is_ok_and(|v| v == "1");
    let mut generated = String::from("// Generated by qx-gpu/build.rs. Do not edit.\n");
    let mut jobs = Vec::new();
    for src in &sources {
        let stem = src.file_stem().unwrap().to_str().unwrap().to_string();
        let mut flat = format!("// Flattened from kernels/{stem}.cu by qx-gpu/build.rs.\n");
        flatten(src, &inc_dir, &mut HashSet::new(), &mut flat);
        let flat_path = out_dir.join(format!("{stem}.cu"));
        fs::write(&flat_path, &flat).unwrap();
        let ents = entries(&flat);
        assert!(!ents.is_empty(), "kernels/{stem}.cu has no extern \"C\" __global__ entry point");
        let konst = stem.to_uppercase();
        generated.push_str(&format!(
            "pub const {konst}: crate::kernel::Module = crate::kernel::Module {{ name: \"{stem}\", source: include_str!(\"{}\"), source_hash: {:#x}, entries: &[{}] }};\n",
            flat_path.display(),
            fnv1a(&flat),
            ents.iter().map(|e| format!("\"{e}\"")).collect::<Vec<_>>().join(", ")
        ));
        if !skip {
            let cubin = out_dir.join(format!("{stem}.cubin"));
            let nvcc = nvcc.clone();
            jobs.push(std::thread::spawn(move || {
                let o = Command::new(&nvcc)
                    .args(["-cubin", "-arch=sm_120a", "-std=c++17", "-O3", "-lineinfo", "-Xptxas=-warn-spills"])
                    .arg("-o").arg(&cubin).arg(&flat_path)
                    .output()
                    .unwrap_or_else(|e| panic!("running {nvcc}: {e}"));
                (stem, o)
            }));
        }
    }
    let mut failed = false;
    for j in jobs {
        let (stem, o) = j.join().unwrap();
        let err = String::from_utf8_lossy(&o.stderr);
        if !o.status.success() {
            failed = true;
            println!("cargo:warning=nvcc failed on kernels/{stem}.cu");
            for l in err.lines() { println!("cargo:warning={l}"); }
        } else if !err.trim().is_empty() {
            for l in err.lines() { println!("cargo:warning=kernels/{stem}.cu: {l}"); }
        }
    }
    if failed {
        panic!("one or more kernels failed to compile with nvcc");
    }
    fs::write(PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("kernels.rs"), generated).unwrap();
}
