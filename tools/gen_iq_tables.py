"""Writes the IQ codebook tables as Rust and CUDA source.

The codebooks are constants of the GGUF formats. They are decoded from llama.cpp's gguf-py (MIT, see
THIRD_PARTY_LICENSES) once, offline; the generated files are checked in and nothing reads gguf-py at build time.

    python3 -I tools/gen_iq_tables.py ~/llama.cpp/gguf-py
"""
import pathlib
import sys

sys.path.insert(0, sys.argv[1])
import numpy as np  # noqa: E402
from gguf import quants  # noqa: E402

root = pathlib.Path(__file__).resolve().parent.parent
tables = {}
for name, cls in [("IQ2S_GRID", quants.IQ2_S), ("IQ3S_GRID", quants.IQ3_S)]:
    cls.init_grid()
    g = cls.grid.reshape(cls.grid_shape).astype(np.int64)
    tables[name] = g
kv = list(quants.IQ4_NL.kvalues)

rs = ["// Generated by tools/gen_iq_tables.py from llama.cpp's gguf-py (MIT). Do not edit.",
      "// IQ2_S: 1024 entries of 8 magnitudes; IQ3_S: 512 entries of 4 magnitudes; IQ4_NL: 16 values.", ""]
cu = ["// Generated by tools/gen_iq_tables.py from llama.cpp's gguf-py (MIT). Do not edit.",
      "// In global memory, not __constant__: lanes index them divergently, which constant memory serializes.",
      "#pragma once", '#include "qx_common.cuh"', ""]
for name, g in tables.items():
    n, w = g.shape
    # Pack each entry little-endian: byte k of the word is magnitude k.
    words = [sum(int(v) << (8 * k) for k, v in enumerate(row)) for row in g]
    ty_rs, ty_cu, fmt = ("u64", "u64", "{:#018x}") if w == 8 else ("u32", "u32", "{:#010x}")
    rs.append(f"pub static {name}: [{ty_rs}; {n}] = [")
    cu.append(f"__device__ const {ty_cu} {name}[{n}] = {{")
    for i in range(0, n, 8):
        chunk = ", ".join(fmt.format(x) for x in words[i:i + 8])
        rs.append(f"    {chunk},")
        cu.append(f"    {chunk}{'ull' if False else ''},")
    rs.append("];\n")
    cu.append("};\n")
rs.append(f"pub static IQ4NL_VALUES: [i8; 16] = [{', '.join(str(v) for v in kv)}];")
cu.append(f"__device__ const i8 IQ4NL_VALUES[16] = {{{', '.join(str(v) for v in kv)}}};")
(root / "crates/qx-quant/src/tables.rs").write_text("\n".join(rs) + "\n")
(root / "kernels/include/qx_iq_tables.cuh").write_text("\n".join(cu) + "\n")
print("wrote tables")
